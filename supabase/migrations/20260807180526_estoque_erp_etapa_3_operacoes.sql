  empresa_id uuid not null references public.empresas(id) on delete cascade,
  numero bigint generated by default as identity,
  tipo text not null check (tipo in ('orcamento','pedido_venda','venda','pedido_compra','recebimento_compra','devolucao_venda','devolucao_compra')),
  status text not null default 'rascunho' check (status in ('rascunho','enviado','aprovado','parcial','concluido','cancelado')),
  parceiro_id uuid,
  contato_id uuid references public.contatos(id) on delete set null,
  documento_origem_id uuid references public.comercial_documentos(id) on delete restrict,
  deposito_id uuid,
  data_emissao date not null default current_date,
  validade_em date,
  previsao_em date,
  subtotal numeric(18,2) not null default 0 check (subtotal >= 0),
  desconto numeric(18,2) not null default 0 check (desconto >= 0),
  acrescimo numeric(18,2) not null default 0 check (acrescimo >= 0),
  frete numeric(18,2) not null default 0 check (frete >= 0),
  total numeric(18,2) not null default 0 check (total >= 0),
  valor_pago numeric(18,2) not null default 0 check (valor_pago >= 0),
  observacao text,
  idempotency_key text,
  versao integer not null default 1,

create or replace function public.comercial_recalcular_documento(p_empresa_id uuid, p_documento_id uuid)
returns void language plpgsql security definer set search_path=public as $$
declare v_subtotal numeric(18,2);
begin
  select coalesce(sum(total),0) into v_subtotal from public.comercial_documento_itens
   where empresa_id=p_empresa_id and documento_id=p_documento_id;
  update public.comercial_documentos set subtotal=v_subtotal,
    total=greatest(0, v_subtotal-desconto+acrescimo+frete), updated_at=now()
   where empresa_id=p_empresa_id and id=p_documento_id;
end $$;

create or replace function public.comercial_salvar_documento(
  p_empresa_id uuid, p_documento_id uuid, p_tipo text, p_parceiro_id uuid, p_contato_id uuid,
  p_deposito_id uuid, p_data_emissao date, p_validade_em date, p_previsao_em date,
  p_desconto numeric, p_acrescimo numeric, p_frete numeric, p_observacao text,
  p_itens jsonb, p_usuario_id uuid
) returns uuid language plpgsql security definer set search_path=public as $$
declare v_id uuid; v_item jsonb; v_catalogo public.catalogo_servicos%rowtype; v_estoque public.estoque_itens%rowtype;
begin
  if p_tipo not in ('orcamento','pedido_venda','venda','pedido_compra') then raise exception 'Tipo de documento invalido.'; end if;
  if jsonb_typeof(p_itens) <> 'array' or jsonb_array_length(p_itens)=0 then raise exception 'Informe ao menos um item.'; end if;
  if p_documento_id is null then
    insert into public.comercial_documentos(empresa_id,tipo,parceiro_id,contato_id,deposito_id,data_emissao,validade_em,previsao_em,desconto,acrescimo,frete,observacao,created_by,updated_by)
    values(p_empresa_id,p_tipo,p_parceiro_id,p_contato_id,p_deposito_id,coalesce(p_data_emissao,current_date),p_validade_em,p_previsao_em,greatest(0,coalesce(p_desconto,0)),greatest(0,coalesce(p_acrescimo,0)),greatest(0,coalesce(p_frete,0)),nullif(trim(p_observacao),''),p_usuario_id,p_usuario_id)
    returning id into v_id;
  else
    select id into v_id from public.comercial_documentos where empresa_id=p_empresa_id and id=p_documento_id and status='rascunho' for update;
    if v_id is null then raise exception 'Somente documentos em rascunho podem ser editados.'; end if;
    update public.comercial_documentos set tipo=p_tipo,parceiro_id=p_parceiro_id,contato_id=p_contato_id,deposito_id=p_deposito_id,
      data_emissao=coalesce(p_data_emissao,current_date),validade_em=p_validade_em,previsao_em=p_previsao_em,
      desconto=greatest(0,coalesce(p_desconto,0)),acrescimo=greatest(0,coalesce(p_acrescimo,0)),frete=greatest(0,coalesce(p_frete,0)),
      observacao=nullif(trim(p_observacao),''),updated_by=p_usuario_id,updated_at=now(),versao=versao+1 where id=v_id;
    delete from public.comercial_documento_itens where empresa_id=p_empresa_id and documento_id=v_id;
  end if;
  if p_parceiro_id is not null and not exists(select 1 from public.comercial_parceiros where empresa_id=p_empresa_id and id=p_parceiro_id and ativo) then raise exception 'Parceiro invalido.'; end if;
  if p_contato_id is not null and not exists(select 1 from public.contatos where empresa_id=p_empresa_id and id=p_contato_id) then raise exception 'Contato invalido.'; end if;
  for v_item in select value from jsonb_array_elements(p_itens) loop
    v_catalogo := null; v_estoque := null;
    if nullif(v_item->>'catalogo_servico_id','') is not null then select * into v_catalogo from public.catalogo_servicos where empresa_id=p_empresa_id and id=(v_item->>'catalogo_servico_id')::uuid and ativo; end if;
    if nullif(v_item->>'estoque_item_id','') is not null then select * into v_estoque from public.estoque_itens where empresa_id=p_empresa_id and id=(v_item->>'estoque_item_id')::uuid and ativo; end if;
    if v_catalogo.id is null and v_estoque.id is null then raise exception 'Item do documento invalido.'; end if;
    insert into public.comercial_documento_itens(empresa_id,documento_id,catalogo_servico_id,estoque_item_id,descricao,unidade,quantidade,valor_unitario,desconto,deposito_id,observacao)
    values(p_empresa_id,v_id,v_catalogo.id,coalesce(v_estoque.id,v_catalogo.estoque_item_id),coalesce(nullif(v_item->>'descricao',''),v_catalogo.nome,v_estoque.nome),
      coalesce(nullif(v_item->>'unidade',''),v_catalogo.unidade,v_estoque.unidade,'un'),greatest(0,(v_item->>'quantidade')::numeric),
      greatest(0,coalesce((v_item->>'valor_unitario')::numeric,v_catalogo.preco,v_estoque.preco_venda,0)),greatest(0,coalesce((v_item->>'desconto')::numeric,0)),
      coalesce(nullif(v_item->>'deposito_id','')::uuid,p_deposito_id,v_catalogo.deposito_padrao_id),nullif(v_item->>'observacao',''));
  end loop;
  perform public.comercial_recalcular_documento(p_empresa_id,v_id);
  return v_id;
end $$;

create or replace function public.comercial_reservar_pedido(p_empresa_id uuid,p_documento_id uuid,p_usuario_id uuid)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_doc public.comercial_documentos%rowtype; v_item record; v_saldo record; v_falta numeric; v_alocar numeric; v_total integer:=0;
begin
  select * into v_doc from public.comercial_documentos where empresa_id=p_empresa_id and id=p_documento_id for update;
  if v_doc.tipo not in ('pedido_venda','venda') then raise exception 'Documento nao e uma venda.'; end if;
  if v_doc.status in ('aprovado','parcial','concluido') then return jsonb_build_object('idempotente',true); end if;
  if v_doc.status not in ('rascunho','enviado') then raise exception 'Documento nao pode ser aprovado.'; end if;
  for v_item in select * from public.comercial_documento_itens where empresa_id=p_empresa_id and documento_id=p_documento_id and estoque_item_id is not null order by estoque_item_id loop
    v_falta:=v_item.quantidade;
    for v_saldo in select s.* from public.estoque_saldos s left join public.estoque_lotes l on l.id=s.lote_id
      where s.empresa_id=p_empresa_id and s.estoque_item_id=v_item.estoque_item_id and s.deposito_id=coalesce(v_item.deposito_id,v_doc.deposito_id)
        and s.saldo_fisico>s.saldo_reservado and coalesce(l.bloqueado,false)=false and (l.validade is null or l.validade>=current_date)
      order by l.validade asc nulls last,s.updated_at for update of s
    loop
      v_alocar:=least(v_falta,v_saldo.saldo_fisico-v_saldo.saldo_reservado);
      update public.estoque_saldos set saldo_reservado=saldo_reservado+v_alocar,versao=versao+1,updated_at=now() where id=v_saldo.id;
      insert into public.estoque_reservas(empresa_id,estoque_item_id,deposito_id,lote_id,quantidade,status,origem_tipo,origem_id,created_by,saldo_id,comercial_documento_item_id)
      values(p_empresa_id,v_item.estoque_item_id,v_saldo.deposito_id,v_saldo.lote_id,v_alocar,'ativa','pedido_venda',p_documento_id,p_usuario_id,v_saldo.id,v_item.id);
      v_falta:=v_falta-v_alocar; v_total:=v_total+1; exit when v_falta<=0;
    end loop;
    if v_falta>0 then raise exception 'Saldo insuficiente para reservar %.',v_item.descricao; end if;
  end loop;
  update public.comercial_documentos set status='aprovado',aprovado_por=p_usuario_id,aprovado_em=now(),updated_at=now() where id=p_documento_id;
  return jsonb_build_object('reservas',v_total);
end $$;

create or replace function public.comercial_liberar_pedido(p_empresa_id uuid,p_documento_id uuid,p_usuario_id uuid,p_cancelar boolean default true)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_reserva record; v_total integer:=0;
begin
  for v_reserva in select * from public.estoque_reservas where empresa_id=p_empresa_id and origem_tipo='pedido_venda' and origem_id=p_documento_id and status='ativa' order by saldo_id for update loop
    update public.estoque_saldos set saldo_reservado=greatest(0,saldo_reservado-(v_reserva.quantidade-v_reserva.consumida)),versao=versao+1,updated_at=now() where empresa_id=p_empresa_id and id=v_reserva.saldo_id;
    update public.estoque_reservas set status='liberada',updated_by=p_usuario_id,updated_at=now() where id=v_reserva.id;
    v_total:=v_total+1;
  end loop;
  if p_cancelar then update public.comercial_documentos set status='cancelado',cancelado_em=now(),updated_by=p_usuario_id,updated_at=now() where empresa_id=p_empresa_id and id=p_documento_id and status<>'concluido'; end if;
  return jsonb_build_object('reservas_liberadas',v_total);
end $$;

create or replace function public.comercial_atender_documento(p_empresa_id uuid,p_documento_id uuid,p_usuario_id uuid,p_idempotency_key text,p_quantidades jsonb default null)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_doc public.comercial_documentos%rowtype; v_item record; v_reserva record; v_linha public.comercial_documento_itens%rowtype; v_estoque_doc uuid; v_tipo text; v_qtd numeric; v_solicitada numeric; v_total integer:=0; v_pendente boolean;
begin
  select * into v_doc from public.comercial_documentos where empresa_id=p_empresa_id and id=p_documento_id for update;
  if not found then raise exception 'Documento nao encontrado.'; end if;
  if v_doc.status='concluido' then return jsonb_build_object('idempotente',true); end if;
  if v_doc.tipo in ('pedido_compra') then v_tipo:='entrada';
  elsif v_doc.tipo in ('pedido_venda','venda') then v_tipo:='saida';
  else raise exception 'Documento nao pode ser atendido.'; end if;
  if v_tipo='saida' and v_doc.status not in ('aprovado','parcial') then perform public.comercial_reservar_pedido(p_empresa_id,p_documento_id,p_usuario_id); end if;
  insert into public.estoque_documentos(empresa_id,tipo,status,origem_tipo,origem_id,idempotency_key,observacao,created_by)
  values(p_empresa_id,v_tipo,'rascunho',v_doc.tipo,p_documento_id,coalesce(nullif(p_idempotency_key,''),p_documento_id::text||':atender'),v_doc.observacao,p_usuario_id)
  on conflict(empresa_id,idempotency_key) do nothing returning id into v_estoque_doc;
  if v_estoque_doc is null then return jsonb_build_object('idempotente',true); end if;
  if v_tipo='entrada' then
    for v_item in select * from public.comercial_documento_itens where empresa_id=p_empresa_id and documento_id=p_documento_id and estoque_item_id is not null and quantidade_atendida<quantidade order by estoque_item_id loop
      v_solicitada:=coalesce((select (value->>'quantidade')::numeric from jsonb_array_elements(coalesce(p_quantidades,'[]'::jsonb)) where value->>'item_id'=v_item.id::text limit 1),v_item.quantidade-v_item.quantidade_atendida);
      v_qtd:=least(v_item.quantidade-v_item.quantidade_atendida,greatest(0,v_solicitada));
      continue when v_qtd<=0;
      insert into public.estoque_documento_itens(empresa_id,documento_id,estoque_item_id,deposito_destino_id,quantidade,custo_unitario)
      values(p_empresa_id,v_estoque_doc,v_item.estoque_item_id,coalesce(v_item.deposito_id,v_doc.deposito_id),v_qtd,v_item.valor_unitario);
      update public.comercial_documento_itens set quantidade_atendida=quantidade_atendida+v_qtd where id=v_item.id;
      v_total:=v_total+1;
    end loop;
  else
    for v_reserva in select * from public.estoque_reservas where empresa_id=p_empresa_id and origem_tipo='pedido_venda' and origem_id=p_documento_id and status='ativa' order by estoque_item_id,saldo_id for update loop
      select * into v_linha from public.comercial_documento_itens where id=v_reserva.comercial_documento_item_id for update;
      v_solicitada:=coalesce((select (value->>'quantidade')::numeric from jsonb_array_elements(coalesce(p_quantidades,'[]'::jsonb)) where value->>'item_id'=v_linha.id::text limit 1),v_linha.quantidade);
      v_qtd:=least(v_reserva.quantidade-v_reserva.consumida,greatest(0,v_solicitada-v_linha.quantidade_atendida));
      continue when v_qtd<=0;
      update public.estoque_saldos set saldo_reservado=greatest(0,saldo_reservado-v_qtd),versao=versao+1,updated_at=now() where id=v_reserva.saldo_id;
      insert into public.estoque_documento_itens(empresa_id,documento_id,estoque_item_id,deposito_origem_id,lote_id,quantidade,custo_unitario)
      select p_empresa_id,v_estoque_doc,v_reserva.estoque_item_id,v_reserva.deposito_id,v_reserva.lote_id,v_qtd,s.custo_medio from public.estoque_saldos s where s.id=v_reserva.saldo_id;
      update public.estoque_reservas set consumida=consumida+v_qtd,status=case when consumida+v_qtd>=quantidade then 'consumida' else status end,consumida_em=case when consumida+v_qtd>=quantidade then now() else consumida_em end,updated_by=p_usuario_id,updated_at=now() where id=v_reserva.id;
      update public.comercial_documento_itens set quantidade_atendida=quantidade_atendida+v_qtd where id=v_linha.id;
      v_total:=v_total+1;
    end loop;
  end if;
  if v_total=0 then raise exception 'Documento sem itens de estoque pendentes.'; end if;
  perform public.estoque_confirmar_documento(p_empresa_id,v_estoque_doc,p_usuario_id);
  select exists(select 1 from public.comercial_documento_itens where empresa_id=p_empresa_id and documento_id=p_documento_id and estoque_item_id is not null and quantidade_atendida<quantidade) into v_pendente;
  update public.comercial_documentos set status=case when v_pendente then 'parcial' else 'concluido' end,concluido_em=case when v_pendente then null else now() end,updated_by=p_usuario_id,updated_at=now() where id=p_documento_id;
  return jsonb_build_object('documento_estoque_id',v_estoque_doc,'itens',v_total);
end $$;

create or replace function public.comercial_devolver_documento(p_empresa_id uuid,p_documento_id uuid,p_usuario_id uuid,p_idempotency_key text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_origem public.comercial_documentos%rowtype; v_devolucao uuid; v_estoque_doc uuid; v_item record; v_tipo_comercial text; v_tipo_estoque text; v_total integer:=0;
begin
  select * into v_origem from public.comercial_documentos where empresa_id=p_empresa_id and id=p_documento_id and status='concluido' for update;
  if not found then raise exception 'Somente documentos concluidos podem ser devolvidos.'; end if;
  if v_origem.tipo='pedido_compra' then v_tipo_comercial:='devolucao_compra'; v_tipo_estoque:='saida';
  elsif v_origem.tipo in ('pedido_venda','venda') then v_tipo_comercial:='devolucao_venda'; v_tipo_estoque:='entrada';
  else raise exception 'Documento nao admite devolucao.'; end if;
  select id into v_devolucao from public.comercial_documentos where empresa_id=p_empresa_id and idempotency_key=p_idempotency_key;
  if v_devolucao is not null then return jsonb_build_object('idempotente',true,'documento_id',v_devolucao); end if;
  insert into public.comercial_documentos(empresa_id,tipo,status,parceiro_id,contato_id,documento_origem_id,deposito_id,data_emissao,subtotal,total,idempotency_key,observacao,concluido_em,created_by,updated_by)
  values(p_empresa_id,v_tipo_comercial,'concluido',v_origem.parceiro_id,v_origem.contato_id,v_origem.id,v_origem.deposito_id,current_date,v_origem.subtotal,v_origem.total,p_idempotency_key,'Devolucao integral do documento '||v_origem.numero,now(),p_usuario_id,p_usuario_id)
  returning id into v_devolucao;
  insert into public.estoque_documentos(empresa_id,tipo,status,origem_tipo,origem_id,idempotency_key,observacao,created_by)
  values(p_empresa_id,v_tipo_estoque,'rascunho',v_tipo_comercial,v_devolucao,p_idempotency_key||':estoque','Devolucao do documento '||v_origem.numero,p_usuario_id) returning id into v_estoque_doc;
  for v_item in select * from public.comercial_documento_itens where empresa_id=p_empresa_id and documento_id=p_documento_id order by estoque_item_id nulls last loop
    insert into public.comercial_documento_itens(empresa_id,documento_id,catalogo_servico_id,estoque_item_id,descricao,unidade,quantidade,quantidade_atendida,valor_unitario,desconto,deposito_id,observacao)
    values(p_empresa_id,v_devolucao,v_item.catalogo_servico_id,v_item.estoque_item_id,v_item.descricao,v_item.unidade,v_item.quantidade_atendida,v_item.quantidade_atendida,v_item.valor_unitario,v_item.desconto,v_item.deposito_id,'Devolucao integral');
    if v_item.estoque_item_id is not null and v_item.quantidade_atendida>0 then
      insert into public.estoque_documento_itens(empresa_id,documento_id,estoque_item_id,deposito_origem_id,deposito_destino_id,quantidade,custo_unitario)
      select p_empresa_id,v_estoque_doc,v_item.estoque_item_id,case when v_tipo_estoque='saida' then coalesce(v_item.deposito_id,v_origem.deposito_id) end,case when v_tipo_estoque='entrada' then coalesce(v_item.deposito_id,v_origem.deposito_id) end,v_item.quantidade_atendida,
        coalesce((select max(custo_medio) from public.estoque_saldos where empresa_id=p_empresa_id and estoque_item_id=v_item.estoque_item_id),v_item.valor_unitario);
      v_total:=v_total+1;
    end if;
  end loop;
  if v_total=0 then raise exception 'Documento sem itens de estoque para devolver.'; end if;
  perform public.estoque_confirmar_documento(p_empresa_id,v_estoque_doc,p_usuario_id);
  return jsonb_build_object('documento_id',v_devolucao,'documento_estoque_id',v_estoque_doc,'itens',v_total);
end $$;

create or replace function public.comercial_registrar_pagamento(p_empresa_id uuid,p_documento_id uuid,p_valor numeric,p_forma text,p_vencimento date,p_confirmar boolean,p_referencia text,p_observacao text,p_idempotency_key text,p_usuario_id uuid)
returns uuid language plpgsql security definer set search_path=public as $$
declare v_doc public.comercial_documentos%rowtype; v_id uuid; v_tipo text;
begin
  select * into v_doc from public.comercial_documentos where empresa_id=p_empresa_id and id=p_documento_id;
  if not found then raise exception 'Documento nao encontrado.'; end if;
  v_tipo:=case when v_doc.tipo in ('pedido_compra','recebimento_compra','devolucao_venda') then 'pagar' else 'receber' end;
  insert into public.comercial_pagamentos(empresa_id,documento_id,tipo,status,forma,valor,vencimento_em,confirmado_em,referencia,observacao,idempotency_key,created_by)
  values(p_empresa_id,p_documento_id,v_tipo,case when p_confirmar then 'confirmado' else 'pendente' end,p_forma,p_valor,p_vencimento,case when p_confirmar then now() end,p_referencia,p_observacao,p_idempotency_key,p_usuario_id)
  returning id into v_id;
  update public.comercial_documentos d set valor_pago=(select coalesce(sum(valor),0) from public.comercial_pagamentos where empresa_id=p_empresa_id and documento_id=p_documento_id and status='confirmado'),updated_at=now() where d.id=p_documento_id;
  return v_id;
end $$;

create or replace function public.estoque_salvar_inventario(p_empresa_id uuid,p_inventario_id uuid,p_deposito_id uuid,p_descricao text,p_tipo_contagem text,p_itens jsonb,p_usuario_id uuid)
returns uuid language plpgsql security definer set search_path=public as $$
declare v_id uuid; v_item jsonb; v_esperado numeric;
begin
  if p_inventario_id is null then
    insert into public.estoque_inventarios(empresa_id,deposito_id,descricao,tipo_contagem,status,iniciado_em,created_by)
    values(p_empresa_id,p_deposito_id,p_descricao,p_tipo_contagem,'em_contagem',now(),p_usuario_id) returning id into v_id;
  else
    select id into v_id from public.estoque_inventarios where empresa_id=p_empresa_id and id=p_inventario_id and status in ('rascunho','em_contagem') for update;
    if v_id is null then raise exception 'Inventario nao pode ser editado.'; end if;
    update public.estoque_inventarios set descricao=p_descricao,tipo_contagem=p_tipo_contagem,updated_at=now() where id=v_id;
  end if;
  for v_item in select value from jsonb_array_elements(p_itens) loop
    if not exists(select 1 from public.estoque_itens where empresa_id=p_empresa_id and id=(v_item->>'estoque_item_id')::uuid and ativo) then raise exception 'Item de inventario invalido.'; end if;
    select coalesce(sum(saldo_fisico),0) into v_esperado from public.estoque_saldos where empresa_id=p_empresa_id and deposito_id=p_deposito_id and estoque_item_id=(v_item->>'estoque_item_id')::uuid;
    insert into public.estoque_inventario_itens(empresa_id,inventario_id,estoque_item_id,saldo_esperado,primeira_contagem,segunda_contagem,quantidade_aprovada,justificativa,contado_por,contado_em)
    values(p_empresa_id,v_id,(v_item->>'estoque_item_id')::uuid,v_esperado,nullif(v_item->>'primeira_contagem','')::numeric,nullif(v_item->>'segunda_contagem','')::numeric,nullif(v_item->>'quantidade_aprovada','')::numeric,nullif(v_item->>'justificativa',''),p_usuario_id,now())
    on conflict(empresa_id,inventario_id,estoque_item_id) where lote_id is null do update set primeira_contagem=excluded.primeira_contagem,segunda_contagem=excluded.segunda_contagem,quantidade_aprovada=excluded.quantidade_aprovada,justificativa=excluded.justificativa,contado_por=p_usuario_id,contado_em=now();
  end loop;
  update public.estoque_inventarios set status='aguardando_aprovacao',encerrado_em=now(),updated_at=now() where id=v_id;
  return v_id;
end $$;

create or replace function public.estoque_aprovar_inventario(p_empresa_id uuid,p_inventario_id uuid,p_usuario_id uuid)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_inv public.estoque_inventarios%rowtype; v_item record; v_doc uuid; v_total integer:=0;
begin
  select * into v_inv from public.estoque_inventarios where empresa_id=p_empresa_id and id=p_inventario_id for update;
  if v_inv.status='aprovado' then return jsonb_build_object('idempotente',true,'documento_id',v_inv.documento_ajuste_id); end if;
  if v_inv.status<>'aguardando_aprovacao' then raise exception 'Inventario nao aguarda aprovacao.'; end if;
  insert into public.estoque_documentos(empresa_id,tipo,status,origem_tipo,origem_id,idempotency_key,observacao,created_by)
  values(p_empresa_id,'ajuste','rascunho','inventario',p_inventario_id,'inventario:'||p_inventario_id::text,v_inv.descricao,p_usuario_id) returning id into v_doc;
  for v_item in select * from public.estoque_inventario_itens where empresa_id=p_empresa_id and inventario_id=p_inventario_id order by estoque_item_id loop
    if coalesce(v_item.quantidade_aprovada,v_item.segunda_contagem,v_item.primeira_contagem) is null then raise exception 'Todos os itens precisam ser contados.'; end if;
    if v_item.divergencia<>0 and nullif(trim(v_item.justificativa),'') is null then raise exception 'Justifique todas as divergencias.'; end if;
    insert into public.estoque_documento_itens(empresa_id,documento_id,estoque_item_id,deposito_destino_id,quantidade)
    values(p_empresa_id,v_doc,v_item.estoque_item_id,v_inv.deposito_id,coalesce(v_item.quantidade_aprovada,v_item.segunda_contagem,v_item.primeira_contagem));
    v_total:=v_total+1;
  end loop;
  perform public.estoque_confirmar_documento(p_empresa_id,v_doc,p_usuario_id);
  update public.estoque_inventarios set status='aprovado',aprovado_por=p_usuario_id,aprovado_em=now(),documento_ajuste_id=v_doc,updated_at=now() where id=p_inventario_id;
  return jsonb_build_object('documento_id',v_doc,'itens',v_total);
end $$;


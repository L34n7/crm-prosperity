select e.id, 'PRINCIPAL', 'Depósito principal', true
from public.empresas e
where not exists (select 1 from public.estoque_depositos d where d.empresa_id = e.id);

insert into public.estoque_configuracoes (empresa_id)
select e.id from public.empresas e on conflict (empresa_id) do nothing;

-- Converte o saldo do MVP em saldo inicial auditavel.
with base as (
  select i.empresa_id, i.id item_id, i.saldo, i.custo_unitario, d.id deposito_id
  from public.estoque_itens i
  join public.estoque_depositos d on d.empresa_id = i.empresa_id and d.principal
  where i.saldo > 0
)
insert into public.estoque_saldos (empresa_id, estoque_item_id, deposito_id, saldo_fisico, custo_medio)
select empresa_id, item_id, deposito_id, saldo, custo_unitario from base
on conflict do nothing;

create or replace function public.estoque_confirmar_documento(
  p_empresa_id uuid, p_documento_id uuid, p_usuario_id uuid default null
) returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_doc public.estoque_documentos%rowtype;
  v_linha record;
  v_saldo public.estoque_saldos%rowtype;
  v_delta numeric(18,6);
  v_antes numeric(18,6);
  v_depois numeric(18,6);
  v_total integer := 0;
begin
  select * into v_doc from public.estoque_documentos
   where id = p_documento_id and empresa_id = p_empresa_id for update;
  if not found then raise exception 'Documento nao encontrado.'; end if;
  if v_doc.status = 'confirmado' then return jsonb_build_object('documento_id', v_doc.id, 'idempotente', true); end if;
  if v_doc.status <> 'rascunho' then raise exception 'Documento nao pode ser confirmado.'; end if;

  for v_linha in select * from public.estoque_documento_itens
    where empresa_id = p_empresa_id and documento_id = v_doc.id order by estoque_item_id
  loop
    select coalesce(sum(saldo_fisico), 0) into v_antes from public.estoque_saldos
      where empresa_id=p_empresa_id and estoque_item_id=v_linha.estoque_item_id;
    if v_doc.tipo = 'transferencia' then
      if v_linha.deposito_origem_id is null or v_linha.deposito_destino_id is null or v_linha.deposito_origem_id = v_linha.deposito_destino_id then
        raise exception 'Informe depositos de origem e destino diferentes.';
      end if;
      perform public.estoque_aplicar_delta(p_empresa_id, v_linha.estoque_item_id, v_linha.deposito_origem_id, v_linha.lote_id, -v_linha.quantidade, coalesce(v_linha.custo_unitario, 0));
      perform public.estoque_aplicar_delta(p_empresa_id, v_linha.estoque_item_id, v_linha.deposito_destino_id, v_linha.lote_id, v_linha.quantidade, coalesce(v_linha.custo_unitario, 0));
    else
      v_delta := case
        when v_doc.tipo in ('entrada','saldo_inicial','estorno') then v_linha.quantidade
        when v_doc.tipo = 'ajuste' then v_linha.quantidade - coalesce((select sum(saldo_fisico) from public.estoque_saldos where empresa_id=p_empresa_id and estoque_item_id=v_linha.estoque_item_id and deposito_id=coalesce(v_linha.deposito_destino_id, v_linha.deposito_origem_id)), 0)
        else -v_linha.quantidade end;
      perform public.estoque_aplicar_delta(p_empresa_id, v_linha.estoque_item_id, coalesce(v_linha.deposito_destino_id, v_linha.deposito_origem_id), v_linha.lote_id, v_delta, coalesce(v_linha.custo_unitario, 0));
    end if;
    select coalesce(sum(saldo_fisico), 0) into v_depois from public.estoque_saldos
      where empresa_id=p_empresa_id and estoque_item_id=v_linha.estoque_item_id;
    insert into public.estoque_movimentacoes (
      empresa_id, estoque_item_id, tipo, quantidade, saldo_anterior, saldo_posterior,
      observacao, created_by, documento_id, deposito_id, lote_id, custo_unitario
    ) values (
      p_empresa_id, v_linha.estoque_item_id, v_doc.tipo, case when v_doc.tipo='ajuste' then abs(v_delta) else v_linha.quantidade end, v_antes, v_depois,
      v_doc.observacao, p_usuario_id, v_doc.id,
      coalesce(v_linha.deposito_destino_id, v_linha.deposito_origem_id), v_linha.lote_id, v_linha.custo_unitario
    );
    v_total := v_total + 1;
  end loop;
  if v_total = 0 then raise exception 'Documento sem itens.'; end if;
  update public.estoque_documentos set status='confirmado', confirmado_em=now() where id=v_doc.id;
  return jsonb_build_object('documento_id', v_doc.id, 'itens', v_total);
end $$;

create or replace function public.estoque_aplicar_delta(
  p_empresa_id uuid, p_item_id uuid, p_deposito_id uuid, p_lote_id uuid,
  p_delta numeric, p_custo_entrada numeric default 0
) returns void language plpgsql security definer set search_path = public as $$
declare v_atual public.estoque_saldos%rowtype; v_novo numeric; v_custo numeric;
begin
  if p_deposito_id is null then raise exception 'Deposito obrigatorio.'; end if;
  insert into public.estoque_saldos (empresa_id, estoque_item_id, deposito_id, lote_id)
  values (p_empresa_id, p_item_id, p_deposito_id, p_lote_id) on conflict do nothing;
  select * into v_atual from public.estoque_saldos where empresa_id=p_empresa_id and estoque_item_id=p_item_id
    and deposito_id=p_deposito_id and lote_id is not distinct from p_lote_id and localizacao_id is null and numero_serie is null for update;
  v_novo := v_atual.saldo_fisico + p_delta;
  if v_novo < v_atual.saldo_reservado then raise exception 'Saldo disponivel insuficiente.'; end if;
  v_custo := case when p_delta > 0 and p_custo_entrada > 0 and v_novo > 0
    then ((v_atual.saldo_fisico * v_atual.custo_medio) + (p_delta * p_custo_entrada)) / v_novo else v_atual.custo_medio end;
  update public.estoque_saldos set saldo_fisico=v_novo, custo_medio=v_custo, versao=versao+1, updated_at=now() where id=v_atual.id;
  update public.estoque_itens set saldo=(select coalesce(sum(saldo_fisico),0) from public.estoque_saldos where empresa_id=p_empresa_id and estoque_item_id=p_item_id),
    custo_unitario=v_custo, versao=versao+1 where empresa_id=p_empresa_id and id=p_item_id;
end $$;

-- Razao derivada dos documentos: nenhuma movimentacao pode ser editada/apagada.
alter table public.estoque_movimentacoes
  add column if not exists documento_id uuid references public.estoque_documentos(id) on delete restrict,
  add column if not exists deposito_id uuid references public.estoque_depositos(id) on delete restrict,
  add column if not exists lote_id uuid references public.estoque_lotes(id) on delete restrict,
  add column if not exists custo_unitario numeric(18,6);

alter table public.estoque_movimentacoes drop constraint if exists estoque_movimentacoes_tipo_check;
alter table public.estoque_movimentacoes add constraint estoque_movimentacoes_tipo_check
  check (tipo in ('saldo_inicial','entrada','saida','ajuste','transferencia','reserva','consumo','liberacao','estorno','venda','execucao'));

create or replace function public.estoque_movimento_imutavel() returns trigger language plpgsql as $$
begin raise exception 'Movimentacoes de estoque sao imutaveis; utilize estorno.'; end $$;
drop trigger if exists estoque_movimentacoes_bloquear_alteracao on public.estoque_movimentacoes;
create trigger estoque_movimentacoes_bloquear_alteracao before update or delete on public.estoque_movimentacoes
for each row execute function public.estoque_movimento_imutavel();

do $$ declare t text; begin
  foreach t in array array['estoque_categorias','estoque_marcas','estoque_depositos','estoque_localizacoes','estoque_lotes','estoque_saldos','estoque_documentos','estoque_documento_itens','estoque_reservas','estoque_custos_historico','estoque_configuracoes']
  loop execute format('alter table public.%I enable row level security', t); execute format('revoke all on public.%I from anon, authenticated', t); end loop;
end $$;


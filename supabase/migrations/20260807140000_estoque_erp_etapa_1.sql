  add column if not exists codigo_barras text,
  add column if not exists categoria_id uuid,
  add column if not exists marca_id uuid,
  add column if not exists controla_lote boolean not null default false,
  add column if not exists controla_validade boolean not null default false,
  add column if not exists controla_serie boolean not null default false,
  add column if not exists versao integer not null default 1;

create table if not exists public.estoque_categorias (
  id uuid primary key default gen_random_uuid(),
  empresa_id uuid not null references public.empresas(id) on delete cascade,
  nome text not null,
  categoria_pai_id uuid references public.estoque_categorias(id) on delete restrict,
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  unique (empresa_id, nome)
);

create table if not exists public.estoque_marcas (
  id uuid primary key default gen_random_uuid(),
  empresa_id uuid not null references public.empresas(id) on delete cascade,
  nome text not null,
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  unique (empresa_id, nome)
);

create table if not exists public.estoque_depositos (
  id uuid primary key default gen_random_uuid(),
  empresa_id uuid not null references public.empresas(id) on delete cascade,
  codigo text not null,
  nome text not null,
  descricao text,
  principal boolean not null default false,
  permite_saldo_negativo boolean not null default false,
  ativo boolean not null default true,
  created_by uuid references public.usuarios(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (empresa_id, codigo),
  unique (empresa_id, id)
);

create unique index if not exists estoque_depositos_principal_uk
  on public.estoque_depositos (empresa_id) where principal and ativo;

create table if not exists public.estoque_localizacoes (
  id uuid primary key default gen_random_uuid(),
  empresa_id uuid not null references public.empresas(id) on delete cascade,
  deposito_id uuid not null,
  codigo text not null,
  nome text not null,
  ativo boolean not null default true,
  created_at timestamptz not null default now(),
  unique (empresa_id, deposito_id, codigo),
  unique (empresa_id, id),
  foreign key (empresa_id, deposito_id)
    references public.estoque_depositos(empresa_id, id) on delete cascade
);

create table if not exists public.estoque_lotes (
  id uuid primary key default gen_random_uuid(),
  empresa_id uuid not null references public.empresas(id) on delete cascade,
  estoque_item_id uuid not null references public.estoque_itens(id) on delete restrict,
  codigo text not null,
  fabricado_em date,
  validade date,
  fabricante text,
  bloqueado boolean not null default false,
  motivo_bloqueio text,
  created_at timestamptz not null default now(),
  unique (empresa_id, estoque_item_id, codigo),
  unique (empresa_id, id)
);

create table if not exists public.estoque_saldos (
  id uuid primary key default gen_random_uuid(),
  empresa_id uuid not null references public.empresas(id) on delete cascade,
  estoque_item_id uuid not null references public.estoque_itens(id) on delete restrict,
  deposito_id uuid not null,
  localizacao_id uuid,
  lote_id uuid,
  numero_serie text,
  saldo_fisico numeric(18, 6) not null default 0 check (saldo_fisico >= 0),
  saldo_reservado numeric(18, 6) not null default 0 check (saldo_reservado >= 0),
  saldo_transito numeric(18, 6) not null default 0 check (saldo_transito >= 0),
  custo_medio numeric(18, 6) not null default 0 check (custo_medio >= 0),
  versao bigint not null default 1,
  updated_at timestamptz not null default now(),
  foreign key (empresa_id, deposito_id) references public.estoque_depositos(empresa_id, id),
  foreign key (empresa_id, localizacao_id) references public.estoque_localizacoes(empresa_id, id),
  foreign key (empresa_id, lote_id) references public.estoque_lotes(empresa_id, id),
  check (saldo_reservado <= saldo_fisico),
  check (numero_serie is null or saldo_fisico <= 1)
);

create unique index if not exists estoque_saldos_dimensoes_uk on public.estoque_saldos (
  empresa_id, estoque_item_id, deposito_id,
  coalesce(localizacao_id, '00000000-0000-0000-0000-000000000000'::uuid),
  coalesce(lote_id, '00000000-0000-0000-0000-000000000000'::uuid),
  coalesce(numero_serie, '')
);

create table if not exists public.estoque_documentos (
  id uuid primary key default gen_random_uuid(),
  empresa_id uuid not null references public.empresas(id) on delete cascade,
  numero bigint generated by default as identity,
  tipo text not null check (tipo in ('saldo_inicial','entrada','saida','ajuste','transferencia','reserva','consumo','liberacao','estorno')),
  status text not null default 'rascunho' check (status in ('rascunho','confirmado','cancelado','estornado')),
  origem_tipo text,
  origem_id uuid,
  idempotency_key text,
  observacao text,
  confirmado_em timestamptz,
  estornado_por_id uuid references public.estoque_documentos(id) on delete restrict,
  created_by uuid references public.usuarios(id) on delete set null,
  created_at timestamptz not null default now(),
  unique (empresa_id, id),
  unique (empresa_id, idempotency_key)
);

create table if not exists public.estoque_documento_itens (
  id uuid primary key default gen_random_uuid(),
  empresa_id uuid not null references public.empresas(id) on delete cascade,
  documento_id uuid not null,
  estoque_item_id uuid not null references public.estoque_itens(id) on delete restrict,
  deposito_origem_id uuid,
  deposito_destino_id uuid,
  localizacao_origem_id uuid,
  localizacao_destino_id uuid,
  lote_id uuid,
  numero_serie text,
  quantidade numeric(18, 6) not null check (quantidade > 0),
  custo_unitario numeric(18, 6) check (custo_unitario is null or custo_unitario >= 0),
  created_at timestamptz not null default now(),
  foreign key (empresa_id, documento_id) references public.estoque_documentos(empresa_id, id) on delete cascade
);

create table if not exists public.estoque_reservas (
  id uuid primary key default gen_random_uuid(),
  empresa_id uuid not null references public.empresas(id) on delete cascade,
  estoque_item_id uuid not null references public.estoque_itens(id) on delete restrict,
  deposito_id uuid not null,
  lote_id uuid,
  quantidade numeric(18, 6) not null check (quantidade > 0),
  consumida numeric(18, 6) not null default 0 check (consumida >= 0),
  status text not null default 'ativa' check (status in ('ativa','consumida','liberada','expirada')),
  origem_tipo text not null,
  origem_id uuid not null,
  expira_em timestamptz,
  created_by uuid references public.usuarios(id) on delete set null,
